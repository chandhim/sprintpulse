/*
 * SprintPulse reports: plain text that pastes cleanly into email, WhatsApp or Slack.
 */
(function (root) {
  'use strict';

  const AREA_ORDER = ['schedule', 'blockers', 'scope', 'overdue'];
  const AREA_NAMES = { schedule: 'Schedule', blockers: 'Blockers', scope: 'Scope', overdue: 'Overdue' };

  function upper(rating) { return String(rating || '').toUpperCase(); }

  function shortDate(value) {
    if (!value) return '?';
    const d = new Date(value);
    if (!Number.isFinite(d.getTime())) return '?';
    const pad = function (n) { return n < 10 ? '0' + n : String(n); };
    return d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate());
  }

  function title(result) {
    return (result.board.name || 'Board') + ' | ' + (result.sprint.name || 'Sprint');
  }

  function datesLine(result) {
    let line = 'Dates: ' + shortDate(result.sprint.start) + ' to ' + shortDate(result.sprint.end);
    if (result.sprint.day && result.sprint.length) line += ' (day ' + result.sprint.day + ' of ' + result.sprint.length + ')';
    return line;
  }

  function itemLine(item, extra) {
    let line = '- ' + (item.key ? item.key + ' ' : '') + item.title;
    line += ' | ' + (item.assignee || 'Unassigned');
    if (extra) line += ' | ' + extra;
    return line;
  }

  function executive(result) {
    const lines = [];
    lines.push('SprintPulse status: ' + title(result));
    lines.push(datesLine(result));
    lines.push('Overall: ' + upper(result.overall.rating) + '. ' + result.overall.reason);
    AREA_ORDER.forEach(function (key) {
      const a = result.areas[key];
      lines.push('- ' + AREA_NAMES[key] + ': ' + upper(a.rating) + '. ' + a.reason);
    });
    const blocked = result.lists.blocked;
    if (blocked.length) {
      const keys = blocked.slice(0, 5).map(function (i) { return i.key || i.title; }).join(', ');
      lines.push('Help needed: unblock ' + keys + (blocked.length > 5 ? ' and ' + (blocked.length - 5) + ' more' : '') + '.');
    } else {
      lines.push('Help needed: none at this time.');
    }
    return lines.join('\n');
  }

  function section(lines, heading, items, extraFn) {
    if (!items.length) return;
    lines.push('');
    lines.push(heading + ' (' + items.length + ')');
    items.forEach(function (item) { lines.push(itemLine(item, extraFn ? extraFn(item) : '')); });
  }

  function team(result, nowValue) {
    const engine = root.SP && root.SP.engine;
    const nowMs = nowValue ? new Date(nowValue).getTime() : new Date(result.generatedAt).getTime();
    const idle = function (item) {
      const days = engine ? engine.daysSince(item.updated, nowMs) : 0;
      return 'no update for ' + days + ' day' + (days === 1 ? '' : 's');
    };
    const c = result.counts;
    const lines = [];
    lines.push('SprintPulse team report: ' + title(result));
    lines.push(datesLine(result) + ' | Overall: ' + upper(result.overall.rating));
    lines.push('Progress: ' + c.done + '/' + c.total + ' done (' + result.progressPct + '%) | In progress: ' +
      c.inprogress + ' | To do: ' + c.todo + ' | Blocked: ' + c.blocked);
    lines.push('Board health score: ' + result.health.score + '/100');

    section(lines, 'BLOCKED', result.lists.blocked, idle);
    section(lines, 'OVERDUE', result.lists.overdue, function (i) { return 'due ' + shortDate(i.due); });
    section(lines, 'ADDED AFTER SPRINT START', result.lists.added, function (i) { return 'added ' + shortDate(i.created); });

    if (result.health.issues.length) {
      lines.push('');
      lines.push('BOARD HEALTH ISSUES (' + result.health.issues.length + ')');
      result.health.issues.forEach(function (h) { lines.push(itemLine(h.item, h.problems.join(', '))); });
    }

    section(lines, 'IN PROGRESS', result.lists.inprogress);
    section(lines, 'TO DO', result.lists.todo);
    section(lines, 'DONE', result.lists.done);
    lines.push('');
    lines.push('Generated by SprintPulse on ' + shortDate(result.generatedAt) + '.');
    return lines.join('\n');
  }

  const api = { executive: executive, team: team, shortDate: shortDate };

  root.SP = root.SP || {};
  root.SP.report = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
